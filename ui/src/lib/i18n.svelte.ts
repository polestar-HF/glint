const dicts: Record<UiLanguage, Record<MessageKey, string>> = { 'zh-CN': zh, 'en-US': en };

export const i18n = $state<{ locale: UiLanguage }>({ locale: 'zh-CN' });

export function setLocale(locale: UiLanguage | string | undefined) {
  i18n.locale = locale === 'en-US' ? 'en-US' : 'zh-CN';
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let s: string = dicts[i18n.locale][key] ?? zh[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, String(vars[k]));
  return s;
}

/** Formats an elapsed duration: "86 ms", "1.2 s". */
export function fmtMs(ms: number | null | undefined): string {
  if (ms == null || !isFinite(ms)) return '';
  if (ms < 1000) return t('unit.ms', { n: Math.round(ms) });
  return t('unit.s', { n: (ms / 1000).toFixed(ms < 10000 ? 1 : 0) });
}
