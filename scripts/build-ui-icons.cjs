#!/usr/bin/env node
// Builds ui/src/lib/icons.ts from qingicon (https://qingicon.com, QingCloud; Apache-2.0).
//
//   node scripts/build-ui-icons.cjs                      fetch the pinned release with `npm pack`
//   node scripts/build-ui-icons.cjs path/to/qingicon.svg  use a local copy of the sprite
//
// qingicon draws on a 48 × 48 grid and ships every glyph twice: `-duotone` (a primary layer in
// currentColor over a lighter secondary layer) and `-fill` (solid). Glint uses duotone as the
// resting look and fill for "on" states (pinned, current page). Only the glyphs in MAP are kept.
// The license travels with them: third_party/qingicon/LICENSE (also bundled into the installer).

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const PACKAGE = '@pitrix/qingicon-react';
const VERSION = '2.1.10';
const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'ui', 'src', 'lib', 'icons.ts');

// Glint name → qingicon name, or [qingicon name, { inset }] where inset (grid units) shrinks the
// glyph inside its box without changing the box.
const MAP = {
  'chevron-down': 'chevron-down',
  'chevron-up': 'chevron-up',
  'chevron-small': ['chevron-down', { inset: 8 }],
  swap: 'left-right',
  copy: 'copy',
  close: 'close',
  pin: 'pin',
  check: 'check',
  alert: 'warning-2',
  info: 'information',
  reset: 'go-back',
  enter: 'go-back-turn-2',
  keyboard: 'keyboard',
  gear: 'gear-2',
  scan: 'scan-code',
  translate: 'language-switch-2',
  palette: 'palette',
  grip: 'drag',
  external: 'share-box',
  eye: 'eye',
  'eye-off': 'eye-off',
  plus: 'add',
  trash: 'trash',
};

function fetchSprite() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'qingicon-'));
  const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
  const tgz = execFileSync(npm, ['pack', `${PACKAGE}@${VERSION}`, '--silent', '--pack-destination', dir], {
    encoding: 'utf8',
    shell: process.platform === 'win32',
  }).trim();
  execFileSync('tar', ['-xzf', path.join(dir, tgz.split(/\r?\n/).pop()), '-C', dir]);
  return path.join(dir, 'package', 'es', 'icons', `qingicon.${VERSION}.svg`);
}

function parts(body, id) {
  const out = [];
  for (const [, tag, attrs] of body.matchAll(/<(\w+)\b([^>]*?)\/?>/g)) {
    const attr = (k) => (attrs.match(new RegExp(`(?:^|\\s)${k}="([^"]*)"`)) || [])[1];
    const d = attr('d');
    if (tag !== 'path' || !d) throw new Error(`${id}: only <path d> elements are supported, found <${tag}>`);
    const fill = attr('fill');
    if (fill && fill !== 'currentColor') throw new Error(`${id}: unexpected fill="${fill}"`);
    const p = { d };
    if (!fill) p.t = 1; // secondary tone
    if (attr('fill-rule') === 'evenodd') p.e = 1;
    out.push(p);
  }
  if (!out.length) throw new Error(`${id}: empty symbol`);
  return out;
}

function main() {
  const spritePath = process.argv[2] || fetchSprite();
  const sprite = fs.readFileSync(spritePath, 'utf8');
  const symbols = new Map();
  for (const m of sprite.matchAll(/<symbol\b[^>]*\bid="([^"]+)"[^>]*>([\s\S]*?)<\/symbol>/g)) symbols.set(m[1], m[2]);
  const get = (id) => {
    if (!symbols.has(id)) throw new Error(`qingicon has no "${id}"`);
    return parts(symbols.get(id), id);
  };

  const fmt = (ps) => `[${ps.map((p) => `{ ${p.t ? 't: 1, ' : ''}${p.e ? 'e: 1, ' : ''}d: '${p.d}' }`).join(', ')}]`;
  const entries = Object.entries(MAP).map(([name, spec]) => {
    const [src, opts = {}] = Array.isArray(spec) ? spec : [spec];
    const duotone = get(`${src}-duotone`);
    const fill = get(`${src}-fill`);
    const key = /^[a-z]+$/.test(name) ? name : `'${name}'`;
    const lines = [`  // qingicon: ${src}`, `  ${key}: {`];
    if (opts.inset) lines.push(`    inset: ${opts.inset},`);
    lines.push(`    duotone: ${fmt(duotone)},`);
    if (JSON.stringify(fill) !== JSON.stringify(duotone)) lines.push(`    fill: ${fmt(fill)},`);
    lines.push('  },');
    return lines.join('\n');
  });

  const ts = `// Generated by scripts/build-ui-icons.cjs. Do not edit by hand: change MAP there and rerun.
//
// Glyphs from qingicon ${VERSION} (https://qingicon.com, ${PACKAGE}), Apache-2.0;
// see third_party/qingicon. Changes: a subset was extracted and the secondary tone is drawn
// as currentColor at reduced opacity instead of a fixed gray.
//
// 48 × 48 grid, filled shapes. \`duotone\` is the resting look; parts with \`t\` are its lighter
// secondary layer. \`fill\` (solid) is for "on" states; when absent the duotone parts are used.

export interface IconPart {
  d: string;
  /** Secondary tone. */
  t?: 1;
  /** fill-rule: evenodd. */
  e?: 1;
}
export interface IconDef {
  duotone: IconPart[];
  fill?: IconPart[];
  /** Shrinks the glyph inside its box, in grid units per side. */
  inset?: number;
}

export const icons = {
${entries.join('\n')}
} satisfies Record<string, IconDef>;

export type IconName = keyof typeof icons;
`;
  fs.writeFileSync(OUT, ts);
  console.log(`${Object.keys(MAP).length} icons written to ${path.relative(ROOT, OUT)}`);
}

main();
